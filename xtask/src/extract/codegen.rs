/// Render the generated recipe-shape catalogue.
///
/// The vocabulary, not the recipes: which serialisers vanilla's data files
/// use, what keys each shape takes, and how many of each there are. No
/// pattern, ingredient or result survives into this file — those are the
/// recipes' contents, and this table is their grammar.
pub fn recipes(data: &Recipes, version: &str) -> String {
    let mut out = String::with_capacity(8 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived from the recipe data pack Minecraft {version}'s own `--server`\n\
          // generator produced, cross-checked against the recipe_serializer registry\n\
          // from the same run. No Mojang file is committed; this is the Rust that\n\
          // resulted from reading them — and it is the shapes, not the recipes: no\n\
          // pattern, ingredient or result appears below.\n\
          //\n\
          // `required` is the key set every recipe of that shape carries; `optional`\n\
          // is what was seen at least once but not everywhere. A reader that treats\n\
          // the optional half as required will reject recipes the game accepts."
    );
    let _ = writeln!(out, "use crate::recipes::RecipeShape;\n");
    let _ = writeln!(
        out,
        "/// The Minecraft version this catalogue was generated from."
    );
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");
    let _ = writeln!(
        out,
        "/// How many recipe files were read, across every namespace and shape."
    );
    let _ = writeln!(out, "pub const RECIPE_COUNT: usize = {};\n", data.total);
    let _ = writeln!(
        out,
        "/// The namespaces the recipe files came from. Vanilla only, on {version};\n\
          /// a datapack adds its own at load time rather than here."
    );
    let namespaces: Vec<String> = data.namespaces.iter().map(|n| format!("{n:?}")).collect();
    let _ = writeln!(
        out,
        "pub static NAMESPACES: &[&str] = &[{}];\n",
        namespaces.join(", ")
    );

    let _ = writeln!(
        out,
        "/// Every recipe shape the vanilla data uses, name-sorted by serialiser.\n\
          /// Each one is an entry of the `recipe_serializer` registry, checked at\n\
          /// extraction against the registry report read beside these files."
    );
    let _ = writeln!(out, "pub static RECIPE_SHAPES: &[RecipeShape] = &[");
    for shape in &data.shapes {
        let list = |values: &[String]| -> String {
            values
                .iter()
                .map(|v| format!("{v:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "    RecipeShape {{ serializer: {:?}, uses: {}, required: &[{}], optional: &[{}] }},",
            shape.serializer,
            shape.uses,
            list(&shape.required),
            list(&shape.optional),
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Serialisers registered on {version} that no vanilla recipe file\n\
          /// exercises. Empty on this version — even the computed `crafting_special_*`\n\
          /// recipes ship marker files — so anything that appears here in a later run\n\
          /// is a serialiser the registry knows and vanilla never uses, which is\n\
          /// exactly the kind of fact to surface rather than absorb."
    );
    let unused: Vec<String> = data
        .unused_serializers
        .iter()
        .map(|s| format!("{s:?}"))
        .collect();
    let _ = writeln!(
        out,
        "pub static UNUSED_SERIALIZERS: &[&str] = &[{}];\n",
        unused.join(", ")
    );

    out
}

/// Render the generated loot-table module.
///
/// The inventory and the vocabulary, never the tables' contents. The
/// vocabulary appears twice on purpose: once from the structured walk that
/// knows an entry type by its position, and once from a pass that counts the
/// `"condition"` / `"function"` strings wherever they sit. `dust-registry`
/// compares the two, for the usual reason.
pub fn loot(data: &LootTables, version: &str) -> String {
    let mut out = String::with_capacity(96 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived from the loot tables Minecraft {version}'s own `--server` generator\n\
          // wrote, cross-checked against the loot condition/function/entry registries.\n\
          // No Mojang file is committed; this is the Rust that resulted from reading\n\
          // them — the inventory of which tables exist and which vocabulary they are\n\
          // written with, and not one drop amount, roll or result."
    );
    let _ = writeln!(out, "/// The Minecraft version this inventory came from.");
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");
    let _ = writeln!(
        out,
        "/// How many loot tables vanilla ships, across every category."
    );
    let _ = writeln!(
        out,
        "pub const TABLE_COUNT: usize = {};\n",
        data.tables.len()
    );

    let _ = writeln!(
        out,
        "/// Every loot table id, e.g. `minecraft:blocks/stone`, sorted — so a lookup\\n\
          /// is a binary search and a duplicate would have been caught at extraction."
    );
    let _ = writeln!(out, "pub static TABLES: &[&str] = &[");
    for table in &data.tables {
        let _ = writeln!(out, "    {table:?},");
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Tables per top-level directory: where vanilla keeps them. Blocks dominate,\n\
          /// because every block that drops anything is a table here."
    );
    let _ = writeln!(out, "pub static CATEGORIES: &[(&str, u32)] = &[");
    for (category, count) in &data.categories {
        let _ = writeln!(out, "    ({category:?}, {count}),");
    }
    let _ = writeln!(out, "];\n");

    let kind_name = |kind: LootKind| match kind {
        LootKind::Condition => "condition",
        LootKind::Function => "function",
        LootKind::Entry => "entry",
    };

    let _ = writeln!(
        out,
        "/// Every condition, function and pool-entry type the vanilla tables use,\\n\
          /// with how many times each appears — read positionally, so a `type` key\\n\\
          /// inside a function's arguments is not mistaken for an entry type. Each\\n\
          /// name is checked at extraction against its registry in the report."
    );
    let _ = writeln!(out, "pub static VOCABULARY: &[(&str, &str, u32)] = &[");
    for usage in &data.vocabulary {
        let _ = writeln!(
            out,
            "    ({:?}, {:?}, {}),",
            kind_name(usage.kind),
            usage.name,
            usage.uses
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// The same condition and function tallies from a second pass that reads\\n\
          /// every string under those two keys with no idea of structure. Where this\\n\\
          /// disagrees with [`VOCABULARY`], one of the two readings of the tree is\\n\\
          /// wrong; see `crates/dust-registry/tests/loot.rs`, which insists it does\\n\\
          /// not disagree."
    );
    let _ = writeln!(out, "pub static SOURCE_COUNTS: &[(&str, &str, u32)] = &[");
    for usage in &data.source {
        let _ = writeln!(
            out,
            "    ({:?}, {:?}, {}),",
            kind_name(usage.kind),
            usage.name,
            usage.uses
        );
    }
    let _ = writeln!(out, "];");
    out
}

/// Render the generated tag-directory module.
///
/// Sorted by (registry, id), members sorted within each row, so both lookups
/// are binary searches. References keep their `#` and are stored fully
/// namespaced — vanilla writes them relative to the defining namespace, which
/// is a spelling, not an identity.
/// The `TagRegistry` variant a registry id spells.
///
/// Derived rather than listed, so adding a fourteenth registry to `TAKEN` is
/// one edit and not two that can disagree. `dust_registry::tags` has the enum
/// and a test that every variant's `name()` round-trips through here.
fn tag_registry_variant(registry: &str) -> Option<String> {
    let bare = registry.strip_prefix("minecraft:")?;
    // `worldgen/biome` is the one nested registry; its variant is the leaf,
    // because `WorldgenBiome` would name a directory rather than a thing.
    let leaf = bare.rsplit('/').next()?;
    let mut out = String::with_capacity(leaf.len());
    for word in leaf.split('_') {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    (!out.is_empty()).then_some(out)
}

pub fn tags(data: &Tags, version: &str) -> Result<String, String> {
    let mut out = String::with_capacity(384 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived from the tag directories of Minecraft {version}'s own data pack,\n\
          // cross-checked against the block report and the registry report: every\n\
          // plain member was verified to exist in its registry's extracted table,\n\
          // and every `#` reference to resolve to another tag of the same registry.\n\
          // No Mojang file is committed; this is the Rust that resulted from reading\n\
          // one.\n\
          //\n\
          // This is the *baseline* layer. Vanilla defines; datapacks overlay. No row\n\
          // here carries `replace`, because vanilla's own files never set it — the\n\
          // field belongs to whatever overlays this later."
    );
    let _ = writeln!(out, "use crate::tags::{{TagDef, TagRegistry}};\n");
    let _ = writeln!(out, "/// The Minecraft version this baseline came from.");
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");

    let _ = writeln!(
        out,
        "/// Every tag of the thirteen registries, sorted by (registry, id)."
    );
    let _ = writeln!(out, "pub static TAGS: &[TagDef] = &[");
    for tag in &data.tags {
        let variant = tag_registry_variant(tag.registry)
            .ok_or_else(|| format!("a tag carries unknown registry {}", tag.registry))?;
        let members: Vec<String> = tag.members.iter().map(|m| format!("{m:?}")).collect();
        let _ = writeln!(
            out,
            "    TagDef {{ registry: TagRegistry::{variant}, id: {:?}, members: &[{}] }},",
            tag.id,
            members.join(", ")
        );
    }
    let _ = writeln!(out, "];");
    Ok(out)
}

/// Render the generated worldgen-vocabulary module for `dust-gen`.
///
/// The Phase 6 engine's vocabulary, deliberately not the world's data: which
/// density-function types vanilla's terrain is written with and what they are
/// called with, the fifteen slots every noise router wires, and the shape of a
/// biome-parameter entry with the five-point nether as its worked example.
/// The overworld's 7,593 ranged entries stay out — those are datapack content
/// a server loads from its world, not constants to freeze.
pub fn worldgen_vocabulary(data: &WorldgenVocabulary, version: &str) -> String {
    let mut out = String::with_capacity(16 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived from the density-function trees and noise settings of Minecraft\n\
          // {version}'s data pack, and from its biome_parameters report. No Mojang file\n\
          // is committed; this is the Rust that resulted from reading them.\n\
          //\n\
          // This is vocabulary, not content. The overworld's parameter expansion —\n\
          // 7,593 ranged entries over 53 biomes — is deliberately absent: it is world\n\
          // data a server reads from its packs at boot, exactly like recipe contents\n\
          // and loot drops, all of which this pipeline also declines to bake in."
    );
    let _ = writeln!(
        out,
        "use crate::worldgen::{{BiomeParameterDimension, DensityFunctionType}};"
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "/// The Minecraft version this vocabulary came from.");
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");

    let _ = writeln!(
        out,
        "/// Every density-function type the vanilla terrain uses, name-sorted, with\n\
          /// how many objects of each appear across all five generator variants\n\
          /// (nested appearances included) and the top-level argument keys each one\n\
          /// is called with, `type` itself excluded. Each name is an entry of the\n\
          /// `worldgen/density_function_type` registry, checked at extraction."
    );
    let _ = writeln!(
        out,
        "pub static DENSITY_FUNCTION_TYPES: &[DensityFunctionType] = &["
    );
    for function in &data.density_function_types {
        let arguments: Vec<String> = function
            .arguments
            .iter()
            .map(|a| format!("{a:?}"))
            .collect();
        let _ = writeln!(
            out,
            "    DensityFunctionType {{ name: {:?}, uses: {}, arguments: &[{}] }},",
            function.name,
            function.uses,
            arguments.join(", ")
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// The noise-router slots, identical across every noise setting on {version}\n\
          /// — checked per file, because one deviant would mean terrain's wiring\n\
          /// changed shape."
    );
    let slots: Vec<String> = data
        .noise_router_slots
        .iter()
        .map(|s| format!("{s:?}"))
        .collect();
    let _ = writeln!(
        out,
        "pub static NOISE_ROUTER_SLOTS: &[&str] = &[{}];\n",
        slots.join(", ")
    );

    let _ = writeln!(
        out,
        "/// The multi-noise parameter names, alphabetically. Every biome-parameter\n\
          /// entry carries exactly these seven."
    );
    let parameters: Vec<String> = super::worldgen::PARAMETER_NAMES
        .iter()
        .map(|p| format!("{p:?}"))
        .collect();
    let _ = writeln!(
        out,
        "pub static BIOME_PARAMETER_NAMES: &[&str] = &[{}];\n",
        parameters.join(", ")
    );

    let _ = writeln!(
        out,
        "/// Per dimension: how many parameter entries the report wrote, how many were\n\
          /// range-shaped rather than point-shaped, and how many distinct biomes they\n\
          /// name. The summary is what stays; the expansion itself is world data."
    );
    let _ = writeln!(
        out,
        "pub static BIOME_PARAMETER_DIMENSIONS: &[BiomeParameterDimension] = &["
    );
    for dimension in &data.dimensions {
        let _ = writeln!(
            out,
            "    BiomeParameterDimension {{ dimension: {:?}, entries: {}, ranged_entries: {}, \
              distinct_biomes: {} }},",
            dimension.dimension,
            dimension.entries,
            dimension.ranged_entries,
            dimension.distinct_biomes
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// The nether's five biome parameter points, verbatim — the golden sample of\n\
          /// the entry format, points all the way down. Values follow\n\
          /// [`BIOME_PARAMETER_NAMES`] order."
    );
    let _ = writeln!(
        out,
        "pub static NETHER_BIOME_POINTS: &[(&str, [f64; 7])] = &["
    );
    for point in &data.nether_points {
        let values: Vec<String> = point.values.iter().map(|v| format!("{v:?}")).collect();
        let _ = writeln!(out, "    ({:?}, [{}]),", point.biome, values.join(", "));
    }
    let _ = writeln!(out, "];");
    out
}

/// Render the datapack registries a server sends during configuration.
///
/// Names only, in the order they go on the wire — see
/// [`super::synced`] for why the contents are absent and when they would stop
/// being. The order is the table's whole content beyond the names, so it is
/// written out explicitly rather than left to a `sort` at run time: two servers
/// that ordered these differently would give a client two different meanings
/// for the same id.
pub fn synced_registries(data: &[super::synced::SyncedRegistry], version: &str) -> String {
    let mut out = String::with_capacity(32 * 1024);
    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
         //\n\
         // The datapack registries a server sends to a joining client during\n\
         // configuration, read from the data pack Minecraft {version}'s jar ships.\n\
         // No Mojang file is committed; this is the Rust that resulted from reading\n\
         // one.\n\
         //\n\
         // Names only. Each entry's contents are omitted on the wire whenever the\n\
         // client has acknowledged the server's known packs, which a vanilla client\n\
         // always does for minecraft:core — captured from a real 1.21.1 server,\n\
         // where every entry of all eleven registries carried no data.\n\
         //\n\
         // The ORDER of the entries is the id order for the rest of a session. It is\n\
         // written here rather than sorted at run time so that two builds of this\n\
         // server cannot disagree about which biome id 37 names."
    );
    let _ = writeln!(out, "use crate::synced::SyncedRegistry;\n");
    let _ = writeln!(out, "/// The Minecraft version these names came from.");
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");

    for registry in data {
        let ident = registry
            .name
            .trim_start_matches("minecraft:")
            .replace('/', "_")
            .to_uppercase();
        let _ = writeln!(
            out,
            "/// `{}` — {} entries.",
            registry.name,
            registry.entries.len()
        );
        let _ = writeln!(out, "static {ident}: &[&str] = &[");
        for entry in &registry.entries {
            let _ = writeln!(out, "    {entry:?},");
        }
        let _ = writeln!(out, "];\n");
    }

    let _ = writeln!(
        out,
        "/// Every datapack registry, in the order a server sends them."
    );
    let _ = writeln!(out, "pub static SYNCED: &[SyncedRegistry] = &[");
    for registry in data {
        let ident = registry
            .name
            .trim_start_matches("minecraft:")
            .replace('/', "_")
            .to_uppercase();
        let _ = writeln!(
            out,
            "    SyncedRegistry {{ name: {:?}, entries: {ident} }},",
            registry.name
        );
    }
    let _ = writeln!(out, "];");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_registry_identifier_drops_minecraft_and_keeps_anything_else() {
        assert_eq!(registry_ident("minecraft:item"), "ITEM");
        assert_eq!(
            registry_ident("minecraft:worldgen/biome_source"),
            "WORLDGEN_BIOME_SOURCE"
        );
        assert_eq!(registry_ident("brigadier:thing"), "BRIGADIER_THING");
    }

    #[test]
    fn a_registry_of_one_contributes_one_sample_row() {
        assert_eq!(registry_sample_ids(1), vec![0]);
        assert_eq!(registry_sample_ids(2), vec![0, 1]);
    }

    #[test]
    fn a_sample_covers_both_ends_and_the_middle() {
        assert_eq!(registry_sample_ids(100), vec![0, 1, 25, 50, 75, 99]);
    }
}
