/// The module name a version's table lives in: `1.21.1` becomes `v1_21_1`.
///
/// Rejects anything that is not a version id so that a typo cannot write
/// outside the generated directory. The extractor takes this string from the
/// command line and turns it into a path, which is the whole reason to be
/// careful about it.
pub fn module_name(version: &str) -> Result<String, String> {
    if version.is_empty()
        || !version
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-' || c == '_')
    {
        return Err(format!(
            "`{version}` is not a version id this can turn into a module name"
        ));
    }
    Ok(format!(
        "v{}",
        version.replace(['.', '-'], "_").to_ascii_lowercase()
    ))
}

/// `configuration` -> `Configuration`, to name the enum variant in
/// `dust-protocol` that this state is.
fn variant(word: &str) -> String {
    let mut chars = word.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// `SCREAMING_CASE` name for a pair's static, e.g. `PLAY_CLIENTBOUND`.
fn static_name(group: &Group) -> String {
    format!(
        "{}_{}",
        group.state.to_ascii_uppercase(),
        group.direction.to_ascii_uppercase()
    )
}

/// Render one protocol version's packet tables.
///
/// The tables land at `state_index * 2 + direction_index` and each one carries
/// the state and direction it is for, so that the direct index the lookup uses
/// is checkable rather than merely believed. See the test in `dust-protocol`
/// that reads those fields back.
pub fn packets(data: &Packets, version: &str, protocol: i32) -> String {
    let mut out = String::with_capacity(64 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
         //\n\
         // Derived from the packet report produced by Minecraft {version}'s own data\n\
         // generators, run against a server jar on the machine that generated this. No\n\
         // Mojang file is committed; this is the Rust that resulted from reading one.\n\
         //\n\
         // A protocol id means nothing on its own: it is an index within one (state,\n\
         // direction) pair, and the same number is a different packet in the next pair.\n\
         // That is why every table here is a pair and never a state.\n"
    );
    let _ = writeln!(
        out,
        "use crate::{{ConnectionState, Direction, PacketTable}};\n"
    );
    let _ = writeln!(
        out,
        "/// The Minecraft version this table was generated from.\n\
         ///\n\
         /// The index module reads this rather than parsing it back out of the module\n\
         /// name, so that the module name stays a file name and nothing more."
    );
    let _ = writeln!(out, "pub const VERSION_NAME: &str = {version:?};\n");

    let _ = writeln!(
        out,
        "/// The number a client puts in its handshake to ask for this version.\n\
         ///\n\
         /// From the jar's own `version.json`, which is the only place it appears:\n\
         /// the packet report names packets and ids and never says which number\n\
         /// selects the table they are in. It is also not derivable from the version\n\
         /// id above — several Minecraft releases share one protocol number, and the\n\
         /// two sequences are unrelated."
    );
    let _ = writeln!(out, "pub const PROTOCOL_NUMBER: i32 = {protocol};\n");

    for group in &data.groups {
        if !group.present {
            continue;
        }
        let name = static_name(group);
        let names: Vec<String> = group.by_id.iter().map(|n| format!("{n:?}")).collect();
        let _ = writeln!(
            out,
            "/// `{}` / `{}`, indexed by protocol id.",
            group.state, group.direction
        );
        let _ = writeln!(out, "static {name}: &[&str] = &[");
        for chunk in names.chunks(4) {
            let _ = writeln!(out, "    {},", chunk.join(", "));
        }
        let _ = writeln!(out, "];");

        // Indices into the table above, ordered by the name at each index, so
        // that the name-to-id direction is a binary search rather than a walk
        // of every packet in the pair. Holes are left out: an id nothing
        // claimed has no name to find.
        let mut by_name: Vec<(usize, &str)> = group
            .by_id
            .iter()
            .enumerate()
            .filter(|(_, name)| !name.is_empty())
            .map(|(i, name)| (i, name.as_str()))
            .collect();
        by_name.sort_by_key(|(_, name)| *name);
        let _ = writeln!(
            out,
            "/// Indices into [`{name}`], ordered by name, for binary search."
        );
        let _ = writeln!(out, "static {name}_BY_NAME: &[u16] = &[");
        for chunk in by_name.chunks(16) {
            let row: Vec<String> = chunk.iter().map(|(i, _)| i.to_string()).collect();
            let _ = writeln!(out, "    {},", row.join(", "));
        }
        let _ = writeln!(out, "];\n");
    }

    let _ = writeln!(
        out,
        "/// Every (state, direction) pair, at `state as usize * 2 + direction as usize`.\n\
         ///\n\
         /// All ten are here whether or not the report had them. `handshake` /\n\
         /// `clientbound` is empty because the server says nothing during a handshake;\n\
         /// leaving the slot out instead would shift every pair after it."
    );
    let _ = writeln!(out, "pub static TABLES: &[PacketTable] = &[");
    for group in &data.groups {
        let (by_id, by_name) = if group.present {
            let name = static_name(group);
            (name.clone(), format!("{name}_BY_NAME"))
        } else {
            ("&[]".to_owned(), "&[]".to_owned())
        };
        let _ = writeln!(
            out,
            "    PacketTable {{ state: ConnectionState::{}, direction: Direction::{}, \
             by_id: {by_id}, by_name: {by_name} }},",
            variant(group.state),
            variant(group.direction)
        );
    }
    let _ = writeln!(out, "];\n");

    packet_samples(&mut out, &data.reported);
    out
}

/// A golden sample of the id-to-name mapping, **taken from the report** rather
/// than from the tables above.
///
/// This exists because the round-trip test in `dust-protocol` cannot catch the
/// defect this extractor is most likely to have. Looking a name up by its id
/// and the id back up by its name goes through the same two tables, and those
/// two agree with each other under *any* consistent numbering — including one
/// that is off by one, or sorted by name instead of by id. A round-trip proves
/// the encoder and the decoder agree with each other, which is not the
/// question. Whether they agree with Minecraft is, and only something derived
/// independently of the derived table can answer it.
///
/// Two deliberate choices make these rows independent:
///
/// - The state and direction are the report's own **strings**, not the enum
///   variants the tables use. The test resolves them by name, so a table that
///   is right about its contents and in the wrong slot — because the enum was
///   reordered, or because the extractor's [`STATES`] and the enum drifted —
///   fails here. Rows carrying the enum could not catch that, because they
///   would move with it.
/// - The rows are in the report's own order, which is alphabetical by packet
///   name, and encodes nothing about the ids.
///
/// Every packet is a row rather than a spread of them. The block table samples
/// because 26,684 rows would be an unreadable file; 223 is not, so the check
/// here is total, and an off-by-one in a corner of `play/clientbound` has
/// nowhere to hide.
fn packet_samples(out: &mut String, reported: &Report) {
    let _ = writeln!(
        out,
        "/// Every packet as Mojang's report states it: state, direction, protocol id,\n\
         /// name. Taken from the report and not from the tables above, with the state\n\
         /// and direction as strings so that nothing here encodes which slot a pair\n\
         /// occupies. See `crates/dust-protocol/tests/` for why a self-consistent\n\
         /// round-trip is not enough on its own."
    );
    let _ = writeln!(
        out,
        "pub static PACKET_SAMPLES: &[(&str, &str, u32, &str)] = &["
    );
    for state in STATES {
        for direction in DIRECTIONS {
            let Some(packets) = reported.get(state).and_then(|s| s.get(direction)) else {
                continue;
            };
            // BTreeMap iterates in key order, which is by packet name — the
            // ordering these rows depend on being independent of the ids.
            for (name, packet) in packets {
                let _ = writeln!(
                    out,
                    "    ({state:?}, {direction:?}, {}, {name:?}),",
                    packet.protocol_id
                );
            }
        }
    }
    let _ = writeln!(out, "];");
}

/// Render the module that lists every version's table.
///
/// This is regenerated from whatever version modules are on disk, so adding
/// 1.21.4 is running the extractor again and not editing anything: a new
/// module appears, a row appears, and every call site that takes a
/// `ProtocolVersion` keeps working.
///
/// The rows are in file-name order, which is not version order — `1.21.10`
/// would sort before `1.21.4`. Nothing here depends on the order, and there is
/// deliberately no `latest()` for that reason: the number that orders protocol
/// versions is `PROTOCOL_NUMBER`, and a caller that wants the newest should say
/// so by comparing those rather than by trusting a position in this list.
pub fn packet_index(modules: &[String]) -> String {
    let mut out = String::with_capacity(4 * 1024);
    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract`. Do not edit.\n\
         //\n\
         // One module and one row per protocol version Dust has a packet table for.\n\
         // Both are regenerated from the modules on disk, so adding a version is\n\
         // running the extractor again rather than editing this file or any caller.\n"
    );
    let _ = writeln!(out, "use crate::{{ProtocolVersion, VersionDef}};\n");
    for module in modules {
        let _ = writeln!(out, "pub mod {module};");
    }
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "/// Every protocol version with a generated packet table, in the order\n\
         /// `ProtocolVersion` indexes them."
    );
    let _ = writeln!(out, "pub static VERSIONS: &[VersionDef] = &[");
    for module in modules {
        let _ = writeln!(
            out,
            "    VersionDef {{ name: {module}::VERSION_NAME, \
             protocol: {module}::PROTOCOL_NUMBER, tables: {module}::TABLES, \
             samples: {module}::PACKET_SAMPLES }},"
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// The versions by name, so a call site can say which one it means without\n\
         /// a fallible lookup.\n\
         ///\n\
         /// A constant here rather than a variant of an enum: a version is a row in a\n\
         /// generated table, and adding one must not be a change to a type that every\n\
         /// `match` in the server would then have to be revisited for."
    );
    let _ = writeln!(out, "pub mod version {{");
    let _ = writeln!(out, "    use super::ProtocolVersion;\n");
    for (index, module) in modules.iter().enumerate() {
        let constant = module.to_ascii_uppercase();
        let _ = writeln!(
            out,
            "    /// Minecraft {}.",
            module.trim_start_matches('v').replace('_', ".")
        );
        let _ = writeln!(
            out,
            "    pub const {constant}: ProtocolVersion = ProtocolVersion::at({index});"
        );
    }
    let _ = writeln!(out, "}}");
    out
}
