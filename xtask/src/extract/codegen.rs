/// Render the generated ore baseline module.
///
/// Two tables, on purpose. [`super::worldgen::Placement`] is what the resolver
/// consumes, and [`super::worldgen::SourceRow`] is the same placements as the
/// files literally write them, copied by a pass that shares no interpretation
/// with the one that produced the first table. `dust-gen` checks one against
/// the other, for the reason [`samples`] gives at length: two tables that agree
/// because they came from the same reading prove only that the reading is
/// self-consistent.
pub fn ores(data: &Ores, version: &str) -> String {
    let mut out = String::with_capacity(64 * 1024);

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
         //\n\
         // Derived from the worldgen data Minecraft {version}'s own `--server` generator\n\
         // produced, run against a server jar on the machine that generated this. No\n\
         // Mojang file is committed; this is the Rust that resulted from reading one.\n\
         //\n\
         // Every group here is named by the block states its placements put down, never\n\
         // by the name of the placed feature, and every group carries those block ids so\n\
         // the reason for its name is on the page. `dirt`, `gravel` and the stone\n\
         // variants are groups like any other: see xtask/src/extract/worldgen.rs for why\n\
         // they are not filtered out.\n"
    );
    let _ = writeln!(out, "use crate::ore_density::{{Attempts, HeightRange}};");
    let _ = writeln!(
        out,
        "use crate::vanilla_ores::{{Dimension, OreGroupDef, Placement, SourceRow}};\n"
    );
    let _ = writeln!(
        out,
        "/// The Minecraft version this table was generated from."
    );
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");

    let _ = writeln!(
        out,
        "/// Each dimension's vertical generation context: the `dimension_type` bounds\n\
         /// narrowed by the generator's own, which is what a relative height anchor\n\
         /// resolves against."
    );
    let _ = writeln!(out, "pub static DIMENSIONS: &[Dimension] = &[");
    for dimension in &data.dimensions {
        let _ = writeln!(
            out,
            "    Dimension {{ id: {:?}, min_y: {}, height: {} }},",
            dimension.id, dimension.min_y, dimension.height
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Every ore placement the world has, with its bounds already resolved to\n\
         /// absolute y."
    );
    let _ = writeln!(out, "pub static PLACEMENTS: &[Placement] = &[");
    for placement in &data.placements {
        let attempts = match placement.attempts {
            Attempts::PerChunk(n) => format!("Attempts::PerChunk({n})"),
            Attempts::RarityFilter { one_in } => {
                format!("Attempts::RarityFilter {{ one_in: {one_in} }}")
            }
        };
        let _ = writeln!(
            out,
            "    Placement {{ id: {:?}, group: {:?}, dimension: {:?}, attempts: {attempts}, \
             vein_size: {}, height: HeightRange {{ min_y: {}, max_y: {} }}, \
             distribution: {:?}, discard_chance_on_air_exposure: {:?} }},",
            placement.id,
            placement.group,
            placement.dimension,
            placement.vein_size,
            placement.min_y,
            placement.max_y,
            placement.distribution,
            placement.discard_chance_on_air_exposure,
        );
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Every ore group, with the block states that put it in the table. The\n\
         /// targets are the derivation, not a description of it: these ids are what\n\
         /// gathered the placements and what named the group."
    );
    let _ = writeln!(out, "pub static GROUPS: &[OreGroupDef] = &[");
    for group in &data.groups {
        let targets: Vec<String> = group.targets.iter().map(|t| format!("{t:?}")).collect();
        let _ = writeln!(
            out,
            "    OreGroupDef {{ name: {:?}, targets: &[{}] }},",
            group.name,
            targets.join(", ")
        );
    }
    let _ = writeln!(out, "];\n");

    ore_source_rows(&mut out, data);
    out
}

/// The independent half of the table: what the files say, before anything read
/// them as meaning something.
///
/// Nothing in a row here has been resolved. The count is the literal the file
/// carries — `"4"`, `"0..=1"`, or the empty string where a placement has no
/// count step at all. Each height bound keeps its spelling and its number
/// separately, so `below_top 10` stays `below_top 10` rather than becoming a y.
/// Each row also carries the two pairs of numbers its dimension's extent was
/// narrowed from, because "which of these two heights did you use" is precisely
/// the mistake that would otherwise be invisible: read the Nether's
/// `dimension_type` height instead of its generator's and every relative bound
/// in it moves by 128 blocks, consistently, in both tables, with nothing to
/// disagree.
fn ore_source_rows(out: &mut String, data: &Ores) {
    let _ = writeln!(
        out,
        "/// Each placement's source facts, copied out of the worldgen files without\n\
         /// being interpreted — a check on the table above that does not share its\n\
         /// reading. See `crates/dust-gen/src/vanilla_ores.rs` for what is done with\n\
         /// them, and why a table that only agrees with itself is not evidence."
    );
    let _ = writeln!(out, "pub static SOURCE_ROWS: &[SourceRow] = &[");
    for row in &data.source {
        let _ = writeln!(
            out,
            "    SourceRow {{ placed_feature: {:?}, configured_feature: {:?}, count: {:?}, \
             rarity: {:?}, size: {}, min_anchor: {:?}, min_value: {}, max_anchor: {:?}, \
             max_value: {}, dimension: {:?}, dimension_type_min_y: {}, \
             dimension_type_height: {}, noise_min_y: {}, noise_height: {}, targets: {:?} }},",
            row.placed_feature,
            row.configured_feature,
            row.count,
            row.rarity,
            row.size,
            row.min_anchor,
            row.min_value,
            row.max_anchor,
            row.max_value,
            row.dimension,
            row.dimension_type_min_y,
            row.dimension_type_height,
            row.noise_min_y,
            row.noise_height,
            row.targets,
        );
    }
    let _ = writeln!(out, "];");
}

/// Render one component value as the constructor call the generated table uses.
fn value(out: &mut String, value: &ItemValue) -> Result<(), String> {
    match value {
        ItemValue::Bool(b) => {
            let _ = write!(out, "Bool({b})");
        }
        ItemValue::Int(i) => {
            let _ = write!(out, "Int({i})");
        }
        ItemValue::Float(f) => {
            // `{:?}` on an f64 is the shortest decimal that parses back to the
            // same bits — the same rule Mojang's serialiser used, which is why
            // `-2.4000000953674316` survives the trip. Checked rather than
            // trusted, per number, because a float literal that reparses to a
            // different value is a wrong number that still compiles.
            let rendered = format!("{f:?}");
            match rendered.parse::<f64>() {
                Ok(back) if back.to_bits() == f.to_bits() => {}
                _ => {
                    return Err(format!(
                        "{f:?} does not re-parse to the value it was rendered from; the \
                         generated table would hold a different number than the report"
                    ))
                }
            }
            let _ = write!(out, "Float({rendered})");
        }
        ItemValue::Str(s) => {
            let _ = write!(out, "Str({s:?})");
        }
        ItemValue::List(items) => {
            let _ = write!(out, "List(&[");
            for (index, item) in items.iter().enumerate() {
                if index > 0 {
                    let _ = write!(out, ", ");
                }
                self::value(out, item)?;
            }
            let _ = write!(out, "])");
        }
        ItemValue::Map(fields) => {
            let _ = write!(out, "Map(&[");
            for (index, (key, field)) in fields.iter().enumerate() {
                if index > 0 {
                    let _ = write!(out, ", ");
                }
                let _ = write!(out, "({key:?}, ");
                self::value(out, field)?;
                let _ = write!(out, ")");
            }
            let _ = write!(out, "])");
        }
    }
    Ok(())
}

/// One line of text for a component value, keys sorted, numbers spelled exactly
/// as the report spells them.
///
/// Not a JSON serialiser and not trying to be: its only job is to render a
/// value tree as a string so two trees can be compared as text. The generated
/// samples are rendered with this, from the report; the tests re-render the
/// *table* with their own copy of the same rule and compare. Two
/// implementations agreeing is the point — a single shared one would agree with
/// itself the way a round-trip does.
fn canonical(value: &ItemValue) -> String {
    match value {
        ItemValue::Bool(b) => b.to_string(),
        ItemValue::Int(i) => i.to_string(),
        ItemValue::Float(f) => format!("{f:?}"),
        ItemValue::Str(s) => format!("{s:?}"),
        ItemValue::List(items) => {
            let rendered: Vec<String> = items.iter().map(canonical).collect();
            format!("[{}]", rendered.join(","))
        }
        ItemValue::Map(fields) => {
            let rendered: Vec<String> = fields
                .iter()
                .map(|(key, field)| format!("{key:?}:{}", canonical(field)))
                .collect();
            format!("{{{}}}", rendered.join(","))
        }
    }
}

/// Render the generated item-components module.
pub fn items(data: &Items, version: &str) -> Result<String, String> {
    let mut out = String::with_capacity(256 * 1024);
    let shared = data.items.len() - data.maps.len();

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
         //\n\
         // Derived from the item report produced by Minecraft {version}'s own data\n\
         // generators, run against a server jar on the machine that generated this. No\n\
         // Mojang file is committed; this is the Rust that resulted from reading one.\n\
         //\n\
         // Every item's *default* data components — what it carries before anything\n\
         // customises it. Values are a generic tree rather than a struct per component\n\
         // type; the argument for that is in `crates/dust-registry/src/items.rs`.\n\
         //\n\
         // The maps are interned: {} items share {} distinct component maps, so {shared}\n\
         // of them are a repeat of one already written down. Numbers are spelled exactly\n\
         // as the report spells them — `-2.4000000953674316` is an f32 printed at f64\n\
         // width, and re-spelling it at f32 width would change the value.\n",
        data.items.len(),
        data.maps.len(),
    );
    let _ = writeln!(
        out,
        "use crate::items::ComponentValue::{{self, Bool, Float, Int, List, Map, Str}};\n"
    );
    let _ = writeln!(
        out,
        "/// The Minecraft version this table was generated from."
    );
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");
    let _ = writeln!(
        out,
        "/// The number of distinct component maps, deduplicated across the items."
    );
    let _ = writeln!(
        out,
        "pub const COMPONENT_MAP_COUNT: usize = {};\n",
        data.maps.len()
    );

    if u16::try_from(data.maps.len()).is_err() {
        return Err(format!(
            "there are {} distinct component maps and the index is u16",
            data.maps.len()
        ));
    }

    for (index, map) in data.maps.iter().enumerate() {
        let sharers = &data.sharers[index];
        let _ = match sharers.len() {
            1 => writeln!(out, "// {}.", sharers[0]),
            n => writeln!(out, "// {}, and {} other items.", sharers[0], n - 1),
        };
        let _ = writeln!(out, "static M{index}: &[(&str, ComponentValue)] = &[");
        for (component, field) in map {
            let _ = write!(out, "    ({component:?}, ");
            value(&mut out, field)?;
            let _ = writeln!(out, "),");
        }
        let _ = writeln!(out, "];");
    }
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "/// The distinct component maps. Reached through [`ITEM_COMPONENTS`], which is\n\
         /// what says which item has which."
    );
    let _ = writeln!(
        out,
        "pub static COMPONENT_MAPS: &[&[(&str, ComponentValue)]] = &["
    );
    for chunk in (0..data.maps.len()).collect::<Vec<_>>().chunks(8) {
        let row: Vec<String> = chunk.iter().map(|index| format!("M{index}")).collect();
        let _ = writeln!(out, "    {},", row.join(", "));
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Indexed by *item protocol id*: which of [`COMPONENT_MAPS`] that item has.\n\
         ///\n\
         /// Indexed rather than named because the item report and the item registry\n\
         /// list the same 1,333 items in the extractor's own check, so the registry's\n\
         /// numbering is already the join key and a second copy of the names here would\n\
         /// be a second thing to keep in step."
    );
    let _ = writeln!(out, "pub static ITEM_COMPONENTS: &[u16] = &[");
    for chunk in data.map_of_item.chunks(16) {
        let row: Vec<String> = chunk.iter().map(usize::to_string).collect();
        let _ = writeln!(out, "    {},", row.join(", "));
    }
    let _ = writeln!(out, "];\n");

    component_samples(&mut out, data)?;
    Ok(out)
}

/// A golden sample of the item-to-components mapping, taken from the report.
///
/// Placed rather than spread. The lesson from the registry tables was that a
/// sample is only evidence where a wrong answer and a right one differ, and for
/// this table that rules out most of the items: 1,004 of the 1,333 share one
/// component map, so shifting the index inside that run changes nothing that
/// could be observed. What *is* observable is an item whose neighbours by
/// protocol id have a different map, so every sampled item is one of those —
/// then an index that slips by one lands on a map that does not match the row.
///
/// One row per distinct map, so every value shape in the report is represented:
/// the four shapes of `minecraft:tool`, the six of `minecraft:food`, the
/// nested effect on `minecraft:chicken`, and — the reason the width check
/// exists — every float literal whose f32 and f64 spellings differ.
fn component_samples(out: &mut String, data: &Items) -> Result<(), String> {
    let _ = writeln!(
        out,
        "/// A sample of the item-to-components mapping as Mojang's report states it,\n\
         /// rendered from the report and not from the table above. Every distinct\n\
         /// component map is represented once, by an item whose protocol-id neighbours\n\
         /// have a different map — see `crates/dust-registry/tests/` for why those two\n\
         /// choices are what make the row evidence of anything."
    );
    let _ = writeln!(out, "pub static COMPONENT_SAMPLES: &[(&str, &str)] = &[");

    let mut rows: Vec<(&str, String)> = Vec::new();
    for (index, map) in data.maps.iter().enumerate() {
        let representative = data.sharers[index]
            .iter()
            .find(|name| is_a_boundary(data, name))
            .unwrap_or(&data.sharers[index][0]);
        let rendered: Vec<String> = map
            .iter()
            .map(|(component, value)| format!("{component:?}:{}", canonical(value)))
            .collect();
        rows.push((
            representative.as_str(),
            format!("{{{}}}", rendered.join(",")),
        ));
    }
    rows.sort_unstable();
    for (item, rendered) in rows {
        // A raw string, because these rows are mostly quotation marks and a
        // hundred backslashes per line would make the one file that has to stay
        // readable across a version bump unreadable.
        //
        // Two hashes and not one: block tags are written `"#minecraft:leaves"`,
        // so `"#` occurs inside 30 of these rows and `r#"..."#` ends at the
        // first of them. That was found by the delimiter being checked rather
        // than assumed, which is the only reason to write a check whose
        // failure mode is a file that does not compile.
        if rendered.contains("\"##") {
            return Err(format!(
                "{item}'s components contain the raw-string delimiter, so the sample row \
                 cannot be written this way"
            ));
        }
        let _ = writeln!(out, "    ({item:?}, r##\"{rendered}\"##),");
    }
    let _ = writeln!(out, "];");
    Ok(())
}

/// True when this item's protocol-id neighbours do not have its component map.
///
/// A sample row on an item in the middle of a run of identical maps cannot fail
/// on an off-by-one, because the wrong answer and the right answer are the same
/// text. This is what keeps the rows on the boundaries, where they differ.
fn is_a_boundary(data: &Items, name: &str) -> bool {
    let Some(id) = data.items.iter().position(|item| item == name) else {
        return false;
    };
    let mine = data.map_of_item[id];
    let before = id.checked_sub(1).map(|i| data.map_of_item[i]);
    let after = data.map_of_item.get(id + 1).copied();
    before.is_none_or(|other| other != mine) || after.is_none_or(|other| other != mine)
}

/// Render the generated command-graph module.
///
/// The graph goes into the repository as a flat array of nodes addressed by
/// index, with children and redirects as indices — including backward ones,
/// because 103 of the 108 redirects point back into `execute` and the graph is
/// genuinely cyclic. Nothing recursive is built at generation time and nothing
/// here resolves a cycle; the walkers in `dust-registry` carry a visited set.
///
/// Fails rather than emitting when a node index would not fit the `u16` the
/// table addresses nodes with. Like the registries' checks, that is a refusal
/// to emit something that would compile and lie.
pub fn commands(data: &Commands, version: &str) -> Result<String, String> {
    let mut out = String::with_capacity(512 * 1024);

    if u16::try_from(data.nodes.len()).is_err() {
        return Err(format!(
            "the command report has {} nodes, and children and redirects are u16 indices",
            data.nodes.len()
        ));
    }

    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived from the command report produced by Minecraft {version}'s own data\n\
          // generators, run against a server jar on the machine that generated this. No\n\
          // Mojang file is committed; this is the Rust that resulted from reading one.\n\
          //\n\
          // The report looks like a tree and is not one: `redirect` names a path back\n\
          // into it, so the real shape is a graph with cycles — every redirect into\n\
          // `execute` is one. That is why this is a flat array of nodes addressed by\n\
          // index rather than an owned tree: a child of node 400 may be node 12.\n\
          //\n\
          // Two nodes here are dead as written: `execute/run` and `return/run` carry no\n\
          // children, no executability and no redirect, while in the game they redirect\n\
          // to the root — which the report cannot say, because a redirect is a path and\n\
          // the root's path is empty. They are emitted as the report states them and\n\
          // named in [`UNREACHABLE`]; see crates/dust-registry/src/commands.rs before\n\
          // building a dispatcher on top of them."
    );
    let _ = writeln!(
        out,
        "use crate::commands::{{ArgumentProperties, CommandDef, NodeKind}};\n"
    );
    let _ = writeln!(
        out,
        "/// The Minecraft version this table was generated from."
    );
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");
    let _ = writeln!(
        out,
        "/// Every node in the command graph. Node 0 is the root."
    );
    let _ = writeln!(out, "pub const NODE_COUNT: usize = {};\n", data.nodes.len());
    let _ = writeln!(
        out,
        "/// Nodes whose path ends in a command the client may run directly."
    );
    let _ = writeln!(
        out,
        "pub const EXECUTABLE_COUNT: usize = {};\n",
        data.executable_count
    );
    let _ = writeln!(
        out,
        "/// The depth of the deepest path from the root, in edges. `/execute if`\n\
          /// style chains go deep; nothing here is recursive, so this is information,\n\
          /// not a limit."
    );
    let _ = writeln!(out, "pub const MAX_DEPTH: usize = {};\n", data.max_depth);

    let _ = writeln!(out, "/// Every command node, in depth-first order with children in name order,\n/// so a subtree is contiguous and reads as one command after another.");
    let _ = writeln!(out, "pub static NODES: &[CommandDef] = &[");
    for node in &data.nodes {
        emit_command_node(&mut out, node)?;
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Nodes that can neither end a command nor continue one. On {version} these are\n\
          /// `execute/run` and `return/run` — see the module header."
    );
    let unreachable: Vec<String> = data.unreachable.iter().map(|i| i.to_string()).collect();
    let _ = writeln!(out, "pub static UNREACHABLE: &[u16] = &[");
    for chunk in unreachable.chunks(16) {
        let _ = writeln!(out, "    {},", chunk.join(", "));
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Every distinct parser and how many argument nodes use it, name-sorted.\n\
          /// Each one is an entry of the `command_argument_type` registry, checked at\n\
          /// extraction against the registry report read beside this file."
    );
    let _ = writeln!(out, "pub static PARSER_USES: &[(&str, u16)] = &[");
    for (parser, uses) in &data.parsers {
        let _ = writeln!(out, "    ({parser:?}, {uses}),");
    }
    let _ = writeln!(out, "];\n");

    command_samples(&mut out, data);
    Ok(out)
}

fn emit_command_node(out: &mut String, node: &Node) -> Result<(), String> {
    let kind = match node.kind {
        CommandKind::Root => "NodeKind::Root",
        CommandKind::Literal => "NodeKind::Literal",
        CommandKind::Argument => "NodeKind::Argument",
    };
    let children: Vec<String> = node.children.iter().map(|i| i.to_string()).collect();
    let redirect = match node.redirect {
        Some(target) => {
            let target = u16::try_from(target).map_err(|_| {
                format!(
                    "{} redirects to node {target}, past the u16 index",
                    node.path
                )
            })?;
            format!("Some({target})")
        }
        None => "None".to_owned(),
    };
    let parser = match &node.parser {
        Some(parser) => format!("Some({parser:?})"),
        None => "None".to_owned(),
    };
    let properties = match &node.properties {
        Some(properties) => {
            let rendered = command_properties(properties).ok_or_else(|| {
                format!(
                    "{} carries properties this extraction cannot spell",
                    node.path
                )
            })?;
            format!("Some({rendered})")
        }
        None => "None".to_owned(),
    };
    let _ = writeln!(
        out,
        "    CommandDef {{ name: {:?}, kind: {kind}, children: &[{}], executable: {}, \
          redirect: {redirect}, parser: {parser}, properties: {properties} }},",
        node.name,
        children.join(", "),
        node.executable
    );
    Ok(())
}

/// One parser-property value as the constructor call the generated table uses.
///
/// `None` for the shapes that carry only strings this module does not name —
/// there are none on 1.21.1, and a new one fails the extraction at parse rather
/// than reaching here.
fn command_properties(properties: &CommandProperties) -> Option<String> {
    let option = |value: &Option<i32>| match value {
        Some(v) => format!("Some({v})"),
        None => "None".to_owned(),
    };
    let option_f64 = |value: &Option<f64>| match value {
        Some(v) => format!("Some({v:?})"),
        None => "None".to_owned(),
    };
    let option_f32 = |value: &Option<f32>| match value {
        Some(v) => format!("Some({v:?})"),
        None => "None".to_owned(),
    };
    Some(match properties {
        CommandProperties::Integer { min, max } => {
            format!(
                "ArgumentProperties::Integer {{ min: {}, max: {} }}",
                option(min),
                option(max)
            )
        }
        CommandProperties::Double { min, max } => {
            format!(
                "ArgumentProperties::Double {{ min: {}, max: {} }}",
                option_f64(min),
                option_f64(max)
            )
        }
        CommandProperties::Float { min, max } => {
            format!(
                "ArgumentProperties::Float {{ min: {}, max: {} }}",
                option_f32(min),
                option_f32(max)
            )
        }
        CommandProperties::Time { min } => format!("ArgumentProperties::Time {{ min: {min} }}"),
        CommandProperties::StringKind(kind) => {
            format!("ArgumentProperties::StringKind({kind:?})")
        }
        CommandProperties::Entity {
            single,
            players_only,
        } => format!(
            "ArgumentProperties::Entity {{ single: {single}, players_only: {players_only} }}"
        ),
        CommandProperties::ScoreHolder { single } => {
            format!("ArgumentProperties::ScoreHolder {{ single: {single} }}")
        }
        CommandProperties::Resource { registry } => {
            format!("ArgumentProperties::Resource {{ registry: {registry:?} }}")
        }
    })
}

/// Golden rows for the command graph, **taken from the report** rather than
/// from anything [`flatten`] derived.
///
/// Every non-root node contributes a `(path, executable, parser)` row, and
/// every redirect a `(source path, target path)` row. Total coverage, not a
/// sample: the packet tables taught that when the rows number hundreds rather
/// than tens of thousands, checking all of them costs one line of output and
/// buys the absence of any corner where an off-by-one hides.
///
/// The paths are what make the rows evidence. The generated table stores no
/// paths at all — a node knows its name and its children's indices — so the
/// test reconstructs each path by walking children from the root, and a wrong
/// child link, a mis-sorted sibling list or a swapped redirect lands on a node
/// whose name spells a different command.
fn command_samples(out: &mut String, data: &Commands) {
    let mut paths: Vec<(String, bool, String)> = Vec::new();
    let mut redirects: Vec<(String, String)> = Vec::new();
    walk_reported(&data.reported, String::new(), &mut |path, node| {
        if !path.is_empty() {
            paths.push((
                path.clone(),
                node.executable,
                node.parser.clone().unwrap_or_default(),
            ));
            if let Some(redirect) = &node.redirect {
                redirects.push((path, redirect.join("/")));
            }
        }
    });

    let _ = writeln!(
        out,
        "/// Every command as Mojang's report states it: its path from the root,\n\
          /// whether it can end a command, and the parser its argument reads input\n\
          /// with (empty for literals and the root). Taken from the report's own tree\n\
          /// and not from the table above; see `crates/dust-registry/tests/commands.rs`."
    );
    let _ = writeln!(out, "pub static PATH_SAMPLES: &[(&str, bool, &str)] = &[");
    for (path, executable, parser) in &paths {
        let _ = writeln!(out, "    ({path:?}, {executable}, {parser:?}),");
    }
    let _ = writeln!(out, "];\n");

    let _ = writeln!(
        out,
        "/// Every redirect as the report writes it: source path to target path. The\n\
          /// 103 rows ending in `execute` are the cycles the flat table exists to hold."
    );
    let _ = writeln!(out, "pub static REDIRECT_SAMPLES: &[(&str, &str)] = &[");
    for (from, to) in &redirects {
        let _ = writeln!(out, "    ({from:?}, {to:?}),");
    }
    let _ = writeln!(out, "];");
}

/// Walk the report's own tree depth-first, handing each node its slash-joined
/// path. This shares nothing with [`super::commands::flatten`] but the types:
/// the golden rows have to be able to disagree with whatever flatten did.
fn walk_reported(
    node: &super::commands::ReportedNode,
    path: String,
    visit: &mut impl FnMut(String, &super::commands::ReportedNode),
) {
    visit(path.clone(), node);
    for (name, child) in &node.children {
        let child_path = if path.is_empty() {
            name.clone()
        } else {
            format!("{path}/{name}")
        };
        walk_reported(child, child_path, visit);
    }
}

/// Render the generated fluid-relationships module.
///
/// Indexed by fluid protocol id, like the item-components table is indexed by
/// item id: the flat registry already carries the names and numbers once, so
/// this table answers only what the registry does not — which block a fluid
/// fills, which bucket carries it, and which still fluid it moves.
pub fn fluids(data: &Fluids, version: &str) -> Result<String, String> {
    let mut out = String::with_capacity(4 * 1024);
    let buckets = data.fluids.iter().filter(|f| f.bucket.is_some()).count();
    let held = data.fluids.iter().filter(|f| f.block.is_some()).count();
    let _ = writeln!(
        out,
        "// Generated by `cargo xtask extract --version {version}`. Do not edit.\n\
          //\n\
          // Derived by joining three reports Minecraft {version}'s own data generators\n\
          // produced: the fluid registry for names and ids, the block report for which\n\
          // blocks hold fluid (the still ones only on this version), and the item\n\
          // registry for which buckets exist. No Mojang file is committed; this is the\n\
          // Rust that resulted from reading them.\n\
          //\n\
          // `minecraft:empty` has no block here on purpose. Air is what an empty fluid\n\
          // looks like in the world, but no report says so, and a table whose value is\n\
          // that it came from the reports does not get to know things they do not say."
    );
    let _ = writeln!(out, "use crate::fluids::FluidDef;\n");
    let _ = writeln!(
        out,
        "/// The Minecraft version this table was generated from."
    );
    let _ = writeln!(out, "pub const DATA_VERSION: &str = {version:?};\n");
    let _ = writeln!(
        out,
        "/// Every fluid's relationships, indexed by fluid protocol id. {} of the {} \
          fluids are held by a block; {} pair with a bucket.",
        held,
        data.fluids.len(),
        buckets
    );
    let _ = writeln!(out, "pub static FLUID_DEFS: &[FluidDef] = &[");
    for fluid in &data.fluids {
        let field = |value: &Option<String>| match value {
            Some(name) => format!("Some({name:?})"),
            None => "None".to_owned(),
        };
        let _ = writeln!(
            out,
            "    FluidDef {{ block: {}, bucket: {}, flowing_of: {} }},",
            field(&fluid.block),
            field(&fluid.bucket),
            field(&fluid.flowing_of),
        );
    }
    let _ = writeln!(out, "];\n");

    fluid_source_rows(&mut out, data);
    Ok(out)
}

/// The independent half of the fluid table: what the three reports say, before
/// anything joined them.
///
/// Same doctrine as the ore baseline's `SOURCE_ROWS`: a table that agrees with
/// itself proves only that its reading is self-consistent. These rows are
/// plain text — `""` for "the reports name nothing here" — copied out by a
/// pass that shares no reading with [`fluids`], and `dust-registry` checks one
/// against the other.
fn fluid_source_rows(out: &mut String, data: &Fluids) {
    let _ = writeln!(
        out,
        "/// Every fluid's relationships as the reports state them, spelled as text\n\
          /// with an empty string where they name nothing. Copied by a pass that does\n\
          /// not share the joins above; see `crates/dust-registry/tests/fluids.rs`."
    );
    let _ = writeln!(
        out,
        "pub static FLUID_SAMPLES: &[(&str, &str, &str, &str)] = &["
    );
    for source in &data.source {
        let _ = writeln!(
            out,
            "    ({:?}, {:?}, {:?}, {:?}),",
            source.name, source.block, source.bucket, source.flowing_of,
        );
    }
    let _ = writeln!(out, "];");
}

